"""Reconciliation import request and response models."""

from enum import StrEnum
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator


class ReconciliationScope(StrEnum):
    """Declared scope of a snapshot.

    Only a ``complete`` snapshot is authoritative for the whole collection and
    may therefore retire Items that are missing from it. A ``partial`` snapshot
    is a delta and can only add or update Items.
    """
    COMPLETE = "complete"
    PARTIAL = "partial"


class ReconciliationRequest(BaseModel):
    """A snapshot of a collection to reconcile against the persisted Items.

    The payload must declare its full scope (``scope``) and its version
    (``version``). Items are keyed by their id, or given as a list of STAC
    Items; in both cases the identity of an Item is taken from the Item's own
    ``id`` field, not from a dictionary key.
    """

    model_config = ConfigDict(extra="forbid")

    version: int = Field(
        ge=0,
        description=(
            "Monotonically increasing version of the snapshot. A snapshot whose "
            "version is older than the last applied version for the collection "
            "is rejected, so replaying an old snapshot cannot overwrite newer data."
        ),
    )
    scope: ReconciliationScope = Field(
        description=(
            "Declared scope of the snapshot. Only a 'complete' snapshot is "
            "authoritative for the collection and may retire Items."
        ),
    )
    items: dict[str, Any] | list[Any] = Field(
        description=(
            "The Items in the snapshot, either a mapping from Item id to Item or "
            "a list of STAC Items."
        ),
    )
    collection_id: str | None = Field(
        default=None,
        description=(
            "Collection id declared by the snapshot. When present it must match "
            "the collection from the request path."
        ),
    )
    item_count: int | None = Field(
        default=None,
        ge=0,
        description=(
            "Number of Items the snapshot declares to contain. A mismatch makes "
            "the snapshot incomplete and prevents any retirement."
        ),
    )
    checksum: str | None = Field(
        default=None,
        description=(
            "Optional SHA-256 checksum of the canonical snapshot Items. A "
            "mismatch makes the snapshot invalid and prevents any retirement."
        ),
    )
    segments: int = Field(
        default=1,
        ge=1,
        description=(
            "Total number of segments the snapshot is split into. Segmented "
            "snapshots are only reconciled once every segment has been received."
        ),
    )
    segment: int = Field(
        default=1,
        ge=1,
        description="1-based index of this segment.",
    )
    dry_run: bool = Field(
        default=False,
        description="When true, only compute and return the actions, write nothing.",
    )

    @model_validator(mode="after")
    def _validate_segment(self) -> "ReconciliationRequest":
        """Reject a segment index that is outside the declared segment count."""
        if self.segment > self.segments:
            raise ValueError(
                f"segment {self.segment} is out of range for a snapshot with "
                f"{self.segments} segment(s)"
            )
        return self


class ReconciliationAction(StrEnum):
    """Actions generated by a reconciliation import."""

    ADD = "add"
    UPDATE = "update"
    RETIRE = "retire"


class ItemAction(BaseModel):
    """A single action generated for an Item."""

    action: ReconciliationAction
    item_id: str


class ReconciliationResult(BaseModel):
    """Outcome of a reconciliation import."""

    collection_id: str
    version: int
    status: Literal["complete", "pending"]
    dry_run: bool = False
    received: int = 0
    added: int = 0
    updated: int = 0
    retired: int = 0
    unchanged: int = 0
    actions: list[ItemAction] = Field(default_factory=list)
    received_segments: list[int] = Field(default_factory=list)
    missing_segments: list[int] = Field(default_factory=list)
